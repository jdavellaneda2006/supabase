-- Arregla clientes_Prueba para que el registro de js/cliente.js funcione.
-- Pégalo completo en Supabase → SQL Editor → Run.
--
-- No borra ni cambia filas existentes, y se puede ejecutar más de una vez.
-- Todo corre en una sola transacción: si algo falla, no se aplica nada.

begin;

-- 1. auth_id guarda el uuid que Supabase Auth le da a cada usuario. La columna
--    id sigue siendo el número automático de la tabla. Si se borra el usuario
--    en Authentication, también se borra su fila aquí.
alter table public."clientes_Prueba"
  add column if not exists auth_id uuid unique
  references auth.users (id) on delete cascade;

-- 2. id tiene que generarse solo, porque el formulario ya no lo envía.
do $$
begin
  if (
    select column_default is null and is_identity = 'NO'
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'clientes_Prueba'
      and column_name = 'id'
  ) then
    alter table public."clientes_Prueba"
      alter column id add generated by default as identity;
  end if;
end $$;

-- 3. rol: se crea si falta, y queda 'cliente' como valor por defecto.
alter table public."clientes_Prueba" add column if not exists rol text;
alter table public."clientes_Prueba" alter column rol set default 'cliente';

-- 4. El formulario solo pide nombre, correo y contraseña, así que estas
--    columnas tienen que poder quedar vacías.
alter table public."clientes_Prueba" alter column telefono  drop not null;
alter table public."clientes_Prueba" alter column direccion drop not null;
alter table public."clientes_Prueba" alter column ciudad    drop not null;

-- 5. Permisos (RLS): cada persona solo puede crear y ver su propia fila.
--    "rol = 'cliente'" impide que alguien se registre a sí mismo como admin
--    mandando otro rol desde la consola del navegador.
alter table public."clientes_Prueba" enable row level security;

grant select, insert on public."clientes_Prueba" to authenticated;

drop policy if exists "clientes_insertan_su_perfil" on public."clientes_Prueba";
create policy "clientes_insertan_su_perfil"
  on public."clientes_Prueba"
  for insert
  to authenticated
  with check (auth.uid() = auth_id and rol = 'cliente');

drop policy if exists "clientes_ven_su_perfil" on public."clientes_Prueba";
create policy "clientes_ven_su_perfil"
  on public."clientes_Prueba"
  for select
  to authenticated
  using (auth.uid() = auth_id);

commit;

-- Hace que la API de Supabase vea de inmediato las columnas nuevas.
notify pgrst, 'reload schema';
